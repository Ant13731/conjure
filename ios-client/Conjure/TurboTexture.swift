    // Create a 1D RGBA8 LUT texture ready for sampling
    static func makeTurboLUTTexture(device: MTLDevice) -> MTLTexture? {
        // 256 x 1 texture, RGBA8Unorm
        let desc = MTLTextureDescriptor.texture2DDescriptor(
            pixelFormat: .rgba32Float,
            width: 256,
            height: 1,
            mipmapped: false
        )
        desc.usage = [.shaderRead]
        desc.storageMode = .shared

        guard let tex = device.makeTexture(descriptor: desc) else { return nil }

        // Fill the texture with uint8 RGBA values
        var texData = [SIMD4<Float>](repeating:SIMD4<Float>(0,0,0,1), count: 256)
        for i in 0..<256 {
            let (r, g, b, a) = turboTableFloat[i]
            texData[i] = SIMD4<Float>(r,g,b,a)
//            texData[iSized + 1] = g
//            texData[iSized + 2] = b
//            texData[iSized + 3] = a
        }

        tex.replace(region: MTLRegionMake2D(0, 0, 256, 1),
                    mipmapLevel: 0,
                    withBytes: texData,
                    bytesPerRow: 256 * MemoryLayout<SIMD4<Float>>.size) // 256 * 4 * # of bytes
        return tex
    }
    
    struct DepthParams {
        var minDepth: Float
        var maxDepth: Float
    }
    
    func formatDepthBufferMetal(
        depthBuffer: CVPixelBuffer,
        minDepth: Float = Float(DataConfig.minDepth),
        maxDepth: Float = Float(DataConfig.maxDepth)
    ) -> CVPixelBuffer? {

        let width = CVPixelBufferGetWidth(depthBuffer)
        let height = CVPixelBufferGetHeight(depthBuffer)

        // 1) Create an output CVPixelBuffer (BGRA8).
        var outPixelBuffer: CVPixelBuffer?
        var status = CVPixelBufferCreate(
            kCFAllocatorDefault,
            width,
            height,
            kCVPixelFormatType_32BGRA,
            nil,
            &outPixelBuffer
        )

        if status != kCVReturnSuccess {
            print("❌ [MetalDepth] Failed to create output CVPixelBuffer. Status=\(status)")
            return nil
        }

        guard let outBuf = outPixelBuffer else {
            print("❌ [MetalDepth] outPixelBuffer is nil after creation.")
            return nil
        }
        
        // 2) Use CVMetalTextureCache to wrap input/output buffers.
        guard let cache = metalTextureCache else {
            print("❌ [MetalDepth] metalTextureCache is nil.")
            return nil
        }
        
        // Output texture
        var dstTexRef: CVMetalTexture?
        let dstFmt = MTLPixelFormat.bgra8Unorm

        status = CVMetalTextureCacheCreateTextureFromImage(
            kCFAllocatorDefault,
            cache,
            outBuf,
            nil,
            dstFmt,
            width,
            height,
            0,
            &dstTexRef
        )
        print("Texture creation status (dst):", status)
        guard let dstTexRefUnwrapped = dstTexRef else {
            print("❌ [MetalDepth] Failed to create CVMetalTexture for output buffer.")
            return nil
        }

        guard let dstTex = CVMetalTextureGetTexture(dstTexRefUnwrapped) else {
            print("❌ [MetalDepth] CVMetalTextureGetTexture returned nil for output texture.")
            return nil
        }

        

        // Input depth texture
        var srcTexRef: CVMetalTexture?
        let srcFmt = MTLPixelFormat.r16Float

        status = CVMetalTextureCacheCreateTextureFromImage(
            kCFAllocatorDefault,
            cache,
            depthBuffer,
            nil,
            srcFmt,
            width,
            height,
            0,
            &srcTexRef
        )
        print("Texture creation status:", status)

        guard let srcTexRefUnwrapped = srcTexRef else {
            print("❌ [MetalDepth] Failed to create CVMetalTexture for depth input.")
            return nil
        }

        guard let srcTex = CVMetalTextureGetTexture(srcTexRefUnwrapped) else {
            print("❌ [MetalDepth] CVMetalTextureGetTexture returned nil for input texture.")
            return nil
        }

        

        // 3) Build command buffer + encoder
        guard let commandBuffer = commandQueue.makeCommandBuffer() else {
            print("❌ [MetalDepth] commandQueue.makeCommandBuffer() returned nil.")
            return nil
        }

        guard let encoder = commandBuffer.makeComputeCommandEncoder() else {
            print("❌ [MetalDepth] makeComputeCommandEncoder() returned nil.")
            return nil
        }

        encoder.setComputePipelineState(pipelineState)
        encoder.setTexture(srcTex, index: 0)
        encoder.setTexture(turboLUTTexture, index: 1)
        encoder.setTexture(dstTex, index: 2)

        var params = DepthParams(minDepth: minDepth, maxDepth: maxDepth)
        encoder.setBytes(&params, length: MemoryLayout<DepthParams>.size, index: 0)

        // 4) Dispatch
        let w = pipelineState.threadExecutionWidth
        let h = pipelineState.maxTotalThreadsPerThreadgroup / w
        let threadsPerThreadgroup = MTLSize(width: w, height: max(1, h), depth: 1)
        let threadsPerGrid = MTLSize(width: width, height: height, depth: 1)

        encoder.dispatchThreads(threadsPerGrid, threadsPerThreadgroup: threadsPerThreadgroup)
        encoder.endEncoding()

        commandBuffer.commit()
        commandBuffer.waitUntilCompleted()

        if let error = commandBuffer.error {
            print("❌ [MetalDepth] GPU command buffer error: \(error.localizedDescription)")
            return nil
        }

        // Success!
        return outBuf
    }

